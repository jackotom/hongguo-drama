const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createMediaAccess } = require('../src/native/media-access');
const media = createMediaAccess('http://localhost:5173');
const file = path.resolve('sample.mp4');
const url = media.localUrl(file);
assert.equal(media.localUrl(file), url);
assert.equal(media.resolveLocal(url), file);
assert.equal(media.resolveLocal('hongguo-local://f/' + Buffer.from(file).toString('base64url')), null);
assert.equal(media.resolveLocal(url + '?path=other'), null);
assert.equal(media.resolveLocal(url.replace('://f/', '://other/')), null);
assert.equal(media.isValid(url), false, 'a token issued for a missing file must fail closed');
const request = (origin, initiatorOrigin = origin) => ({ headers: new Headers(origin ? { Origin: origin } : {}), initiatorOrigin });
assert.equal(media.corsHeaders(request('null'))['Access-Control-Allow-Origin'], 'null');
assert.equal(media.corsHeaders(request('http://localhost:5173'))['Access-Control-Allow-Origin'], 'http://localhost:5173');
assert.equal(media.corsHeaders(request('https://untrusted.example')), null);
assert.equal(media.corsHeaders(request('null', 'https://untrusted.example')), null);
assert.equal(media.corsHeaders(request('http://localhost:5173', 'null')), null);
media.clear(); assert.equal(media.resolveLocal(url), null);

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'hongguo-media-access-'));
const real = path.join(root, 'episode.mp4');
fs.writeFileSync(real, 'original-video');
const issued = media.localUrl(real, () => true);
assert.equal(media.isValid(issued), true);
fs.writeFileSync(real, 'replacement-content-of-different-size');
assert.equal(media.isValid(issued), false, 'same-path content rewrite must invalidate the old token');
assert.equal(media.resolveLocal(issued), null, 'an invalidated token must be retired, never revived');
const reissued = media.localUrl(real, () => true);
assert.notEqual(reissued, issued, 'a changed file must receive a fresh token');
assert.equal(media.isValid(reissued), true);
fs.unlinkSync(real);
fs.writeFileSync(real, 'third-content');
assert.equal(media.isValid(reissued), false, 'a replaced file must invalidate the prior token');
const missing = media.localUrl(path.join(root, 'not-yet.mp4'), () => true);
assert.equal(media.isValid(missing), false, 'a file created after issuance must never become valid');
fs.writeFileSync(path.join(root, 'not-yet.mp4'), 'late-content');
assert.equal(media.isValid(missing), false, 'creating the file later must not revive a null-identity token');
fs.rmSync(root, { recursive: true, force: true });

console.log('PASS media access: stable opaque capability, fail-closed identity, no path fallback, origin checks, cleanup');
